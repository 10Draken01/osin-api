CREATE TABLE producto (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(120) NOT NULL,
    descripcion     VARCHAR2(500),
    precio_unitario NUMBER(10, 2) NOT NULL,
    existencia      NUMBER(10) DEFAULT 0 NOT NULL,
    activo          NUMBER(1) DEFAULT 1 NOT NULL,
    version_lock    NUMBER(10) DEFAULT 0 NOT NULL,

    CONSTRAINT pk_producto PRIMARY KEY (id),
    CONSTRAINT uq_producto_nombre UNIQUE (nombre),
    CONSTRAINT ck_producto_precio CHECK (precio_unitario >= 0),
    CONSTRAINT ck_producto_existencia CHECK (existencia >= 0),
    CONSTRAINT ck_producto_activo CHECK (activo IN (0, 1))
);

CREATE TABLE pedido (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    folio               VARCHAR2(30) NOT NULL,
    estado              VARCHAR2(20) DEFAULT 'BORRADOR' NOT NULL,
    fecha_creacion      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_cancelacion   TIMESTAMP,

    CONSTRAINT pk_pedido PRIMARY KEY (id),
    CONSTRAINT uq_pedido_folio UNIQUE (folio),
    CONSTRAINT ck_pedido_estado
        CHECK (estado IN ('BORRADOR', 'CONFIRMADO', 'CANCELADO')),
    CONSTRAINT ck_pedido_cancelacion
        CHECK (
            (estado = 'CANCELADO' AND fecha_cancelacion IS NOT NULL)
            OR
            (estado <> 'CANCELADO' AND fecha_cancelacion IS NULL)
        )
);

CREATE TABLE pedido_detalle (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pedido_id       NUMBER NOT NULL,
    producto_id     NUMBER NOT NULL,
    cantidad        NUMBER(10) NOT NULL,
    precio_unitario NUMBER(10, 2) NOT NULL,
    subtotal        NUMBER(12, 2)
                    GENERATED ALWAYS AS (cantidad * precio_unitario) VIRTUAL,

    CONSTRAINT pk_pedido_detalle PRIMARY KEY (id),
    CONSTRAINT fk_detalle_pedido
        FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT fk_detalle_producto
        FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT uq_detalle_pedido_producto UNIQUE (pedido_id, producto_id),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario >= 0)
);

CREATE INDEX ix_detalle_producto ON pedido_detalle (producto_id);
CREATE INDEX ix_pedido_estado ON pedido (estado);

CREATE SEQUENCE seq_pedido_folio
    START WITH 4
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE OR REPLACE VIEW vw_pedido_resumen AS
SELECT
    p.id,
    p.folio,
    p.estado,
    p.fecha_creacion,
    p.fecha_actualizacion,
    p.fecha_cancelacion,
    NVL(SUM(d.subtotal), 0) AS total,
    COUNT(d.id) AS numero_partidas
FROM pedido p
LEFT JOIN pedido_detalle d
    ON d.pedido_id = p.id
GROUP BY
    p.id,
    p.folio,
    p.estado,
    p.fecha_creacion,
    p.fecha_actualizacion,
    p.fecha_cancelacion;


COMMIT;