CREATE TABLE PRODUCTOS (
    ID              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE          VARCHAR2(120 CHAR) NOT NULL,
    DESCRIPCION     VARCHAR2(500 CHAR),
    PRECIO_UNITARIO NUMBER(12,2) NOT NULL,
    EXISTENCIAS     NUMBER(10) DEFAULT 0 NOT NULL,
    ACTIVO          NUMBER(1) DEFAULT 1 NOT NULL,
    VERSION_LOCK    NUMBER(19) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID),
    CONSTRAINT UQ_PRODUCTOS_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO_UNITARIO > 0),
    CONSTRAINT CK_PRODUCTOS_EXISTENCIAS CHECK (EXISTENCIAS >= 0),
    CONSTRAINT CK_PRODUCTOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);


CREATE TABLE PEDIDOS (
    ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    FOLIO               VARCHAR2(30 CHAR) NOT NULL,
    ESTADO              VARCHAR2(20 CHAR) DEFAULT 'BORRADOR' NOT NULL,
    FECHA_CREACION      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_CANCELACION   TIMESTAMP,
    VERSION_LOCK        NUMBER(19) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
    CONSTRAINT UQ_PEDIDOS_FOLIO UNIQUE (FOLIO),

    CONSTRAINT CK_PEDIDOS_ESTADO
        CHECK (
            ESTADO IN (
                'BORRADOR',
                'CONFIRMADO',
                'COMPLETADO',
                'CANCELADO'
            )
        ),

    CONSTRAINT CK_PEDIDOS_CANCELACION
        CHECK (
            (ESTADO = 'CANCELADO' AND FECHA_CANCELACION IS NOT NULL)
            OR
            (ESTADO <> 'CANCELADO' AND FECHA_CANCELACION IS NULL)
        )
);


CREATE TABLE PEDIDOS_DETALLES (
    ID                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PEDIDO_ID         NUMBER(19) NOT NULL,
    PRODUCTO_ID       NUMBER(19) NOT NULL,
    CANTIDAD          NUMBER(10) NOT NULL,
    -- Precio del producto al momento de crear el pedido.
    -- El subtotal no se guarda porque se obtiene con CANTIDAD * PRECIO_UNITARIO
    PRECIO_UNITARIO   NUMBER(12,2) NOT NULL,

    CONSTRAINT PK_PEDIDOS_DETALLES
        PRIMARY KEY (ID),

    CONSTRAINT FK_PEDIDOS_DETALLES_PEDIDO
        FOREIGN KEY (PEDIDO_ID)
        REFERENCES PEDIDOS (ID),

    CONSTRAINT FK_PEDIDOS_DETALLES_PRODUCTO
        FOREIGN KEY (PRODUCTO_ID)
        REFERENCES PRODUCTOS (ID),

    CONSTRAINT UQ_PEDIDOS_DETALLES_PEDIDO_PRODUCTO
        UNIQUE (PEDIDO_ID, PRODUCTO_ID),

    CONSTRAINT CK_PEDIDOS_DETALLES_CANTIDAD
        CHECK (CANTIDAD > 0),

    CONSTRAINT CK_PEDIDOS_DETALLES_PRECIO
        CHECK (PRECIO_UNITARIO > 0)
);


CREATE INDEX IX_PEDIDOS_DETALLES_PRODUCTO
    ON PEDIDOS_DETALLES (PRODUCTO_ID);

CREATE INDEX IX_PEDIDOS_ESTADO
    ON PEDIDOS (ESTADO);


-- Empieza en 4 porque 02_data.sql inserta PED-000001 a PED-000003
CREATE SEQUENCE SEQ_PEDIDOS_FOLIO
    START WITH 4
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;


-- Vista solo para consultar desde SQL Developer los totales de cada pedido.
-- La API no la usa, el backend calcula los importes
CREATE OR REPLACE VIEW VW_PEDIDO_RESUMEN AS
SELECT
    P.ID,
    P.FOLIO,
    P.ESTADO,
    P.FECHA_CREACION,
    P.FECHA_ACTUALIZACION,
    P.FECHA_CANCELACION,
    NVL(SUM(D.CANTIDAD * D.PRECIO_UNITARIO), 0) AS TOTAL,
    COUNT(D.ID) AS NUMERO_PARTIDAS
FROM PEDIDOS P
LEFT JOIN PEDIDOS_DETALLES D
    ON D.PEDIDO_ID = P.ID
GROUP BY
    P.ID,
    P.FOLIO,
    P.ESTADO,
    P.FECHA_CREACION,
    P.FECHA_ACTUALIZACION,
    P.FECHA_CANCELACION;
